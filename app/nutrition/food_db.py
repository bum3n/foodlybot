def normalize_food_name(text: str) -> str:
    """Удаляет лишние символы и приводит к нижнему регистру."""
    t = text.lower().strip()
    for char in [",", ".", "!", "?", "(", ")", '"', "'", ";", ":"]:
        t = t.replace(char, "")
    return " ".join(t.split())


def find_in_food_database(query: str) -> Optional[Tuple[str, Dict[str, Any]]]:
    """
    Поиск продукта в локальной базе по точному совпадению,
    синонимам или вхождению подстроки.
    """
    norm = normalize_food_name(query)
    
    # 1. Точное совпадение ключа
    if norm in STANDARD_FOOD_DATABASE:
        return norm, STANDARD_FOOD_DATABASE[norm]
        
    # 2. Совпадение по синонимам
    for key, data in STANDARD_FOOD_DATABASE.items():
        if norm == key:
            return key, data
        for syn in data.get("synonyms", []):
            if norm == syn:
                return key, data
                
    # 3. Вхождение подстроки (например 'яичница из 2 яиц' -> 'яичница' или 'рис отварной' -> 'рисовая каша')
    for key, data in STANDARD_FOOD_DATABASE.items():
        if key in norm or norm in key:
            return key, data
        for syn in data.get("synonyms", []):
            if syn in norm or norm in syn:
                return key, data
                
    return None
